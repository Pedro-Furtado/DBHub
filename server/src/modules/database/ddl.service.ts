import type pg from 'pg'
import { conflict } from '../../lib/errors.ts'
import type { ColumnDefinition, CreateTableInput } from './ddl.schemas.ts'
import { ident, qualified } from './pg-utils.ts'

const literal = (value: string) => `'${value.replace(/'/g, "''")}'`

export function columnType(column: Pick<ColumnDefinition, 'type' | 'typeArgs' | 'isArray'>) {
  if (column.type.includes('.')) {
    // Enum "schema.nome": cada parte validada por regex e citada com ident()
    const [schema, name] = column.type.split('.') as [string, string]
    const base = qualified(schema, name)
    return column.isArray ? `${base}[]` : base
  }
  const base = column.typeArgs && ['varchar', 'numeric'].includes(column.type) ? `${column.type}(${column.typeArgs.replace(/\s/g, '')})` : column.type
  return column.isArray ? `${base}[]` : base
}

export function columnSql(column: ColumnDefinition, singlePk: boolean) {
  const parts = [ident(column.name), columnType(column)]
  if (column.isIdentity) parts.push('generated by default as identity')
  if (column.isPrimaryKey && singlePk) parts.push('primary key')
  else if (!column.nullable) parts.push('not null')
  if (column.defaultValue) parts.push(`default ${column.defaultValue}`)
  if (column.unique && !column.isPrimaryKey) parts.push('unique')
  if (column.references) {
    const r = column.references
    parts.push(`references ${qualified(r.schema, r.table)} (${ident(r.column)})`)
    if (r.onDelete !== 'no action') parts.push(`on delete ${r.onDelete}`)
  }
  return parts.join(' ')
}

/**
 * Monta o DDL de criação de tabela.
 * Nomes passam por regex + aspas (ident) e tipos vêm de uma lista fechada;
 * só o "valor padrão" é expressão livre — igual ao que o usuário já pode fazer no SQL Editor.
 */
export function buildCreateTableSql(input: CreateTableInput) {
  const pkColumns = input.columns.filter((c) => c.isPrimaryKey)
  const singlePk = pkColumns.length === 1

  const lines = input.columns.map((c) => `  ${columnSql(c, singlePk)}`)
  if (pkColumns.length > 1) lines.push(`  primary key (${pkColumns.map((c) => ident(c.name)).join(', ')})`)

  const statements = [`create table ${qualified(input.schema, input.name)} (\n${lines.join(',\n')}\n);`]
  if (input.comment) statements.push(`comment on table ${qualified(input.schema, input.name)} is ${literal(input.comment)};`)
  return statements.join('\n\n')
}

export async function listSchemas(client: pg.PoolClient) {
  const { rows } = await client.query<{ name: string }>(`
    select nspname as name
      from pg_namespace
     where nspname not in ('pg_catalog', 'information_schema', 'pg_toast')
       and nspname not like 'pg_temp_%' and nspname not like 'pg_toast_temp_%'
       and has_schema_privilege(oid, 'USAGE')
     order by nspname = 'public' desc, nspname
  `)
  return rows.map((r) => r.name)
}

/** Cria a tabela numa transação: ou cria tudo (tabela + comentário), ou nada. */
export async function createTable(client: pg.PoolClient, input: CreateTableInput) {
  const { rows } = await client.query(
    `select 1 from pg_class c join pg_namespace n on n.oid = c.relnamespace where n.nspname = $1 and c.relname = $2`,
    [input.schema, input.name],
  )
  if (rows.length) throw conflict(`Já existe uma tabela ${input.schema}.${input.name}`, 'TABLE_EXISTS')

  const sql = buildCreateTableSql(input)
  await client.query('BEGIN')
  try {
    await client.query(sql)
    await client.query('COMMIT')
  } catch (error) {
    await client.query('ROLLBACK').catch(() => undefined)
    throw error
  }
  return { schema: input.schema, name: input.name, sql }
}
