import type pg from 'pg'
import { notFound } from '../../lib/errors.ts'

export type TableInfo = {
  schema: string
  name: string
  kind: 'table' | 'view'
  rowEstimate: number | null
  sizeBytes: number
}

export type ColumnInfo = {
  name: string
  type: string
  nullable: boolean
  defaultValue: string | null
  isPrimaryKey: boolean
  isUnique?: boolean
  /** Coluna de senha: o banco aplica hash bcrypt automaticamente (trigger do DBHub) */
  isHashed?: boolean
  isIdentity?: boolean
  comment?: string | null
  foreignKey?: { table: string; column: string; constraint?: string }
  /** Coluna do tipo enum (ou array de enum): tipo e valores permitidos, na ordem */
  enum?: { schema: string; name: string; values: string[] }
}

const SYSTEM_SCHEMAS = `('pg_catalog', 'information_schema', 'pg_toast')`

export async function listTables(client: pg.PoolClient): Promise<TableInfo[]> {
  const { rows } = await client.query<{
    schema: string
    name: string
    relkind: string
    row_estimate: string | null
    size_bytes: string
  }>(`
    select n.nspname as schema,
           c.relname as name,
           c.relkind,
           -- reltuples = -1: tabela nunca analisada (estimativa desconhecida)
           case when c.reltuples < 0 then null else c.reltuples::bigint end as row_estimate,
           case when c.relkind in ('r','p','m') then pg_total_relation_size(c.oid) else 0 end as size_bytes
      from pg_class c
      join pg_namespace n on n.oid = c.relnamespace
     where c.relkind in ('r', 'p', 'v', 'm')
       and n.nspname not in ${SYSTEM_SCHEMAS}
       and n.nspname not like 'pg_temp_%'
       and not c.relispartition
     order by n.nspname = 'public' desc, n.nspname, c.relname
  `)
  return rows.map((r) => ({
    schema: r.schema,
    name: r.name,
    kind: r.relkind === 'v' || r.relkind === 'm' ? 'view' : 'table',
    rowEstimate: r.row_estimate === null ? null : Number(r.row_estimate),
    sizeBytes: Number(r.size_bytes),
  }))
}

export async function getColumns(client: pg.PoolClient, schema: string, table: string): Promise<ColumnInfo[]> {
  const { rows } = await client.query<{
    name: string
    type: string
    nullable: boolean
    default_value: string | null
    is_pk: boolean
    is_unique: boolean
    is_hashed: boolean
    is_identity: boolean
    comment: string | null
    fk_table: string | null
    fk_column: string | null
    fk_constraint: string | null
    enum_schema: string | null
    enum_name: string | null
    enum_values: string[] | null
  }>(
    `
    select a.attname as name,
           format_type(a.atttypid, a.atttypmod) as type,
           not a.attnotnull as nullable,
           -- Colunas identity não têm default em pg_attrdef: mostramos como padrão para a UI não exigir valor
           coalesce(
             pg_get_expr(d.adbin, d.adrelid),
             case a.attidentity when 'a' then 'generated always as identity'
                                when 'd' then 'generated by default as identity' end
           ) as default_value,
           coalesce(pk.is_pk, false) as is_pk,
           exists (
             select 1 from pg_constraint u
              where u.conrelid = c.oid and u.contype = 'u' and u.conkey = array[a.attnum]::int2[]
           ) as is_unique,
           exists (
             select 1 from pg_trigger tg
              where tg.tgrelid = c.oid and not tg.tgisinternal
                and tg.tgname = left('dbhub_hash_' || a.attname, 63)
           ) as is_hashed,
           a.attidentity <> '' as is_identity,
           col_description(c.oid, a.attnum) as comment,
           fk.fk_table,
           fk.fk_column,
           fk.fk_constraint,
           en.enum_schema,
           en.enum_name,
           en.enum_values
      from pg_attribute a
      join pg_class c on c.oid = a.attrelid
      join pg_namespace n on n.oid = c.relnamespace
      left join pg_attrdef d on d.adrelid = a.attrelid and d.adnum = a.attnum
      left join lateral (
        select true as is_pk
          from pg_index i
         where i.indrelid = c.oid and i.indisprimary and a.attnum = any(i.indkey)
      ) pk on true
      left join lateral (
        select fn.nspname || '.' || fc.relname as fk_table, fa.attname as fk_column, con.conname as fk_constraint
          from pg_constraint con
          join pg_class fc on fc.oid = con.confrelid
          join pg_namespace fn on fn.oid = fc.relnamespace
          join pg_attribute fa on fa.attrelid = con.confrelid
                              and fa.attnum = con.confkey[array_position(con.conkey, a.attnum)]
         where con.conrelid = c.oid and con.contype = 'f' and a.attnum = any(con.conkey)
         limit 1
      ) fk on true
      left join lateral (
        -- enum direto ou array de enum (typelem aponta para o tipo do elemento)
        select tn.nspname::text as enum_schema,
               et.typname::text as enum_name,
               array(select e.enumlabel::text from pg_enum e where e.enumtypid = et.oid order by e.enumsortorder) as enum_values
          from pg_type t
          join pg_type et on et.oid = case when t.typcategory = 'A' then t.typelem else t.oid end
          join pg_namespace tn on tn.oid = et.typnamespace
         where t.oid = a.atttypid and et.typtype = 'e'
      ) en on true
     where n.nspname = $1 and c.relname = $2
       and a.attnum > 0 and not a.attisdropped
     order by a.attnum
    `,
    [schema, table],
  )

  if (rows.length === 0) throw notFound(`Tabela ${schema}.${table} não encontrada`, 'TABLE_NOT_FOUND')

  return rows.map((r) => ({
    name: r.name,
    type: r.type,
    nullable: r.nullable,
    defaultValue: r.default_value,
    isPrimaryKey: r.is_pk,
    isUnique: r.is_unique,
    isHashed: r.is_hashed,
    isIdentity: r.is_identity,
    comment: r.comment,
    ...(r.enum_schema && r.enum_name ? { enum: { schema: r.enum_schema, name: r.enum_name, values: r.enum_values ?? [] } } : {}),
    ...(r.fk_table && r.fk_column ? { foreignKey: { table: r.fk_table, column: r.fk_column, constraint: r.fk_constraint ?? undefined } } : {}),
  }))
}

export async function getDatabaseStats(client: pg.PoolClient) {
  const { rows } = await client.query<{ version: string; size_bytes: string; table_count: number }>(`
    select current_setting('server_version') as version,
           pg_database_size(current_database()) as size_bytes,
           (select count(*)::int
              from pg_class c join pg_namespace n on n.oid = c.relnamespace
             where c.relkind in ('r','p') and not c.relispartition
               and n.nspname not in ${SYSTEM_SCHEMAS}) as table_count
  `)
  const row = rows[0]!
  return {
    version: `PostgreSQL ${row.version.split(' ')[0]}`,
    sizeBytes: Number(row.size_bytes),
    tableCount: row.table_count,
  }
}
